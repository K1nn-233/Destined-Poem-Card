#!/usr/bin/env python3
"""Generate a Tavern Helper JS script that loads compact geography data."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[3]
SOURCE_DIR = ROOT / "content" / "geography"
COMPACT_DIR = ROOT / "dist" / "local" / "geography" / "compact"
OUTPUT = ROOT / "dist" / "local" / "geography" / "load_compact.js"


def load_yaml(path: Path) -> dict[str, Any]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def current_date_version() -> str:
    utc_plus_eight = timezone(timedelta(hours=8))
    return datetime.now(utc_plus_eight).strftime("%Y%m%d")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Tavern Helper compact geography loader")
    parser.add_argument("--source", type=Path, default=SOURCE_DIR)
    parser.add_argument("--compact", type=Path, default=COMPACT_DIR)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--variable", default="runtime_geo_compact_data")
    parser.add_argument(
        "--version",
        help="UTC+8 date version YYYYMMDD; append a suffix for same-day updates",
    )
    args = parser.parse_args()

    version = str(args.version) if args.version is not None else current_date_version()
    data = {
        "version": version,
        "places": load_yaml(args.compact / "place.yaml").get("places") or [],
        "edges": load_yaml(args.compact / "edges.yaml").get("edges") or [],
    }
    literal = json.dumps(data, ensure_ascii=False, indent=2)
    variable_literal = json.dumps(args.variable, ensure_ascii=False)
    version_literal = json.dumps(version)
    script = f"""// Generated by tools/geography/scripts/generate_tavern_loader.py
// Loads compact geography data into chat-level variables for prompt templates.
(() => {{
  const VARIABLE = {variable_literal};
  const VERSION = {version_literal};
  const load = () => {{
  const variables = getVariables({{ type: 'chat' }});
  const existing = variables[VARIABLE];
  const existingVersion = existing?.version == null ? '' : String(existing.version);
  const skipReminderKey = `${{VARIABLE}}.skip_update_prompt.${{VERSION}}`;

  const getSkipReminder = () => {{
    try {{
      return globalThis.localStorage?.getItem(skipReminderKey) === '1';
    }} catch (_error) {{
      return false;
    }}
  }};

  const setSkipReminder = () => {{
    try {{
      globalThis.localStorage?.setItem(skipReminderKey, '1');
    }} catch (_error) {{
      // Ignore storage errors; skipping this run is still safe.
    }}
  }};

  if (existing && existingVersion === VERSION) {{
    return `skip ${{VARIABLE}}: existing version ${{existingVersion}} is current`;
  }}

  if (existing && existingVersion !== VERSION) {{
    if (getSkipReminder()) {{
      return `skip ${{VARIABLE}} v${{VERSION}}: user disabled reminders for this version`;
    }}

    const choice = globalThis.prompt(
      [
        `检测到 ${{VARIABLE}} 有新版本：当前 ${{existingVersion || '未知'}}，新版本 ${{VERSION}}。`,
        '输入 y 覆盖加载新版本。',
        '输入 n 跳过本次，之后仍会提醒。',
        '输入 s 跳过并且本版本不再提醒；以后有新版本会重新提醒。',
      ].join('\\n'),
      'n',
    );
    const normalizedChoice = String(choice || '').trim().toLowerCase();

    if (['s', 'skip', '不再提醒'].includes(normalizedChoice)) {{
      setSkipReminder();
      return `skip ${{VARIABLE}} v${{VERSION}}: user disabled reminders for this version`;
    }}

    if (!['y', 'yes', '覆盖'].includes(normalizedChoice)) {{
      return `skip ${{VARIABLE}} v${{VERSION}}: user declined overwrite`;
    }}
  }}

  const data = {literal};
  insertOrAssignVariables({{ [VARIABLE]: data }}, {{ type: 'chat' }});
  return `loaded ${{VARIABLE}} v${{VERSION}}: ${{data.places.length}} places, ${{data.edges.length}} edges`;
  }};
  // Character scripts can survive a new chat; each chat owns its own graph.
  // Tavern Helper removes this iframe-scoped listener when the script unloads.
  eventOn(tavern_events.CHAT_CHANGED, load);
  return load();
}})();
"""
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(script, encoding="utf-8", newline="\n")
    print(f"written={args.output} version={version} places={len(data['places'])} edges={len(data['edges'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
